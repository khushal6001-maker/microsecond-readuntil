# Tables of five columns or more need the smaller size in an IEEE column.
NARROW = {"tab:agree", "tab:entropy", "tab:rules", "tab:costs"}

# Node separations in the arena picture, tightened to the IEEE column measure. See the note
# in the module docstring: the acmart geometry is 0.42 pt too wide.
ARENA_SPACING = [("right=14mm of", "right=12mm of")]


def main() -> int:
    src = SRC.read_text(encoding="utf-8")

    m_abs = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", src, re.S)
    if not m_abs:
        print("could not find the abstract", file=sys.stderr)
        return 1
    abstract = m_abs.group(1).strip()

    body = src[src.index("\\section{Introduction}"):src.index("\\begin{thebibliography}")]

    # ---- section cross-references -----------------------------------------------------
    body = body.replace(BS + "S" + BS + "ref{sec:gap}--" + BS + "S" + BS + "ref{sec:causes}",
                        "Sections~" + BS + "ref{sec:gap}--" + BS + "ref{sec:causes}")
    body = body.replace(BS + "S" + BS + "ref{", "Section~" + BS + "ref{")
    body = body.replace(BS + "S1.", "Section~I.")
    if BS + "S" in body:
        at = body.index(BS + "S")
        print("unconverted section sign: " + repr(body[at - 60:at + 20]), file=sys.stderr)
        return 1

    # ---- run-in headings --------------------------------------------------------------
    body = re.sub(r"\\paragraph\{([^}]*)\}",
                  lambda m: BS + "textbf{" + m.group(1) + ".}", body)

    # ---- table geometry ---------------------------------------------------------------
    def fix_table(m: re.Match) -> str:
        block = m.group(0)
        label = re.search(r"\\label\{(tab:[^}]*)\}", block)
        size = BS + ("scriptsize" if label and label.group(1) in NARROW else "footnotesize")
        return block.replace(BS + "small", BS + "centering" + NL + size)

    body = re.sub(r"\\begin\{table\}.*?\\end\{table\}", fix_table, body, flags=re.S)

    # ---- the arena state machine, tightened to the IEEE column ------------------------
    arena = re.search(r"\\begin\{figure\}\[t\].*?\\end\{figure\}", body, re.S)
    if not arena or "fig:arena" not in arena.group(0):
        print("could not find the arena figure", file=sys.stderr)
        return 1
    tight = arena.group(0)
    for old, new in ARENA_SPACING:
        if old not in tight:
            print("arena spacing " + repr(old) + " not found", file=sys.stderr)
            return 1
        tight = tight.replace(old, new)
    body = body.replace(arena.group(0), tight)

    out = (PREAMBLE + TOPMATTER
           + BS + "begin{abstract}" + NL + abstract + NL + BS + "end{abstract}" + NL + NL
           + KEYWORDS + body + BIBLIOGRAPHY)

    DST.write_text(out, encoding="utf-8")
    print("wrote " + str(DST.relative_to(REPO)) + " (" + str(len(out.splitlines())) + " lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
